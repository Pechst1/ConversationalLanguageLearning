"""Owner decision (12 Nov 2026): a sentence the learner builds or writes is said to nobody.

«Wir können bei Lila bleiben, Marin.» asked the learner to decide where «Marin» goes in
the French, which is no part of the rule being practised and only confuses. So in the
grammar part of the day — La Forge, the recall drills, any rule drill — an item the
learner builds (tiles, a word bank, a line to rebuild) or writes (a translation, a
repair, «Write what you said, correctly», a free sentence with a model answer) carries
no vocative: no name or form of address set off by a comma at either end of its prompt,
its tiles, its model answer or its accepted answers. A name that is part of the sentence
(«chez Lila») stays. The story's own dialogue, reading panels and the items where the
learner only recognises or chooses keep their names.

The one strip is :func:`app.services.answer_acceptance.strip_vocative`; this module is
where each kind of item applies it:

* :func:`unaddressed_item` — a Forge / Atelier payload item (``word_bank``, a repair,
  an output-ladder item, the paragraph). Applied when a set is generated by the model,
  when an item is served (``item_bank.public_item``) and when an answer is graded
  (``AtelierCorrectionService``), so an item stored before the decision is served and
  graded the same way, without its name.
* :func:`unaddressed_task` — a journey recall task (tiles, word bank, unscramble,
  short answer, transform), applied where the planner seats it on the day.
* :func:`unaddressed_exercise` — a brief or error-repair exercise from the model.

The item bank strips its own items (``item_bank.without_vocative``) because it knows
which slot was the name.
"""
from __future__ import annotations

import hashlib
import re
from collections import Counter
from dataclasses import replace
from typing import Any

from app.services.answer_acceptance import addressed_names, opens_on_a_person, strip_vocative

#: The generation prompt's half of the rule; what comes back is stripped all the same.
NO_ADDRESS_INSTRUCTION = (
    "No sentence the learner builds or writes (word_bank answers and chips, transform expected_answer, "
    "output_ladder example_answer, produce example_answer, and the English meaning or prompt that asks for them) "
    "is said to someone by name: never a name or form of address set off by a comma at the start or end "
    "(never «On peut rester chez Lila, Marin.», «Margaux, tu viens ?», «Merci, madame.»). "
    "A name inside the sentence is fine («Je reste chez Lila.»); a character's own line in « » may address people."
)

#: Fewest words a build or write item keeps once its address is out («Merci, madame.»
#: → «Merci.» is no sentence to build); below it the item is not posed as a build.
MIN_WORDS = 3

#: French fields of a payload item: the sentence the learner produces, and what it starts from.
_FRENCH_FIELDS = ("correct_answer", "expected_answer", "example_answer", "source", "source_fr", "source_fragment")
_FRENCH_LISTS = ("accepted_answers", "accepted_fr")
#: Fields whose words are someone else's or are no text at all.
_KEEP = frozenset(
    {
        "id", "tokens", "answer_tokens", "character", "coach", "scene", "requirements", "lesson_external_id",
        "bank_unit", "bank_frame", "bank_fingerprint", "target_span", "wrong_span", "type", "mode", "round",
        "instruction_key", "rule_panel", "label_l10n", "follow_up_key",
    }
)


def _letter_words(text: str) -> int:
    return len(re.findall(r"[^\W\d_]+", text))


def _answer_of(item: dict[str, Any]) -> str | None:
    for field in ("correct_answer", "expected_answer", "example_answer"):
        value = item.get(field)
        if isinstance(value, str) and value.strip():
            return value
    return None


def is_build_or_write(item: Any) -> bool:
    """A payload item the learner builds or writes: a word bank, a repair, an output
    item or the paragraph. A fill, a sort or a pair is answered by choosing."""

    if not isinstance(item, dict):
        return False
    if item.get("answer_tokens") is not None or item.get("expected_answer") is not None:
        return True
    return isinstance(item.get("example_answer"), str)


def item_names(item: dict[str, Any]) -> list[str]:
    """The addresses the item's French says (its key and every accepted answer)."""

    texts = [item.get(field) for field in _FRENCH_FIELDS]
    for field in _FRENCH_LISTS:
        texts.extend(item.get(field) or [])
    names: list[str] = []
    for text in texts:
        if isinstance(text, str):
            names.extend(name for name in addressed_names(text) if name not in names)
    return names


def _strip_native(value: Any, names: list[str]) -> Any:
    if isinstance(value, str):
        return strip_vocative(value, names)
    if isinstance(value, list):
        return [_strip_native(child, names) for child in value]
    if isinstance(value, dict):
        return {key: (child if key in _KEEP else _strip_native(child, names)) for key, child in value.items()}
    return value


def _fold(token: str) -> str:
    return token.strip().casefold()


def _without_address_tokens(tokens: list[str], names: list[str]) -> tuple[list[str], list[str], bool] | None:
    """``tokens`` (one per word, punctuation apart) with the address taken out: the kept
    tokens, the removed ones, and whether the sentence now opens on a new word."""

    for name in names:
        words = [_fold(word) for word in name.split()]
        span = len(words)
        folded = [_fold(token) for token in tokens]
        # «…, Marin .» / «…, Marin ?» / a question then its answer: the name before an end mark.
        for start in range(len(tokens) - span):
            if folded[start] != "," or folded[start + 1: start + 1 + span] != words:
                continue
            after = start + 1 + span
            if after == len(tokens) or folded[after] in {".", "?", "!", "…"}:
                return tokens[:start] + tokens[after:], tokens[start:after], False
        # «Margaux , tu …»: the name first.
        if folded[:span] == words and len(tokens) > span and folded[span] == ",":
            return tokens[span + 1:], tokens[: span + 1], True
    return None


def _strip_tiles(item: dict[str, Any], names: list[str], answer: str) -> dict[str, Any] | None:
    answer_tokens = [str(token) for token in item.get("answer_tokens") or []]
    chips = [str(token) for token in item.get("tokens") or []]
    cut = _without_address_tokens(answer_tokens, names)
    if cut is None:
        return None
    kept, removed, opened = cut
    if not kept:
        return None
    if opened:
        kept[0] = kept[0][:1].upper() + kept[0][1:]
    left = Counter(removed)
    shown: list[str] = []
    for chip in chips:
        if left[chip] > 0:
            left[chip] -= 1
            continue
        shown.append(chip)
    if sum(left.values()):
        return None
    if opened:
        first = _fold(kept[0])
        for index, chip in enumerate(shown):
            if _fold(chip) == first:
                shown[index] = kept[0]
                break
    from app.services.item_bank import _join, normalize

    if normalize(_join(kept)) != normalize(answer):
        return None
    if Counter(map(_fold, kept)) - Counter(map(_fold, shown)):
        return None
    return {**item, "answer_tokens": kept, "tokens": shown}


def unaddressed_item(item: Any) -> Any:
    """A payload item said to nobody, ``item`` itself when it is no build or write item
    or names nobody, or ``None`` when what is left is no sentence to build or write."""

    if not is_build_or_write(item):
        return item
    names = item_names(item)
    if not names:
        return item
    out: dict[str, Any] = {}
    for key, value in item.items():
        if key in _FRENCH_FIELDS and isinstance(value, str):
            out[key] = strip_vocative(value, names)
        elif key in _FRENCH_LISTS and isinstance(value, list):
            out[key] = list(dict.fromkeys(strip_vocative(answer, names) if isinstance(answer, str) else answer for answer in value))
        elif key in _KEEP:
            out[key] = value
        else:
            out[key] = _strip_native(value, names)
    answer = _answer_of(out)
    if answer is None or _letter_words(answer) < MIN_WORDS or addressed_names(answer) or opens_on_a_person(answer):
        return None
    if item.get("answer_tokens") is not None:
        return _strip_tiles(out, names, answer)
    return out


def unaddressed_payload(node: Any) -> Any:
    """:func:`unaddressed_item` over a set payload, a round's prompt payload or one item.
    An item that cannot be said to nobody stays as it was: a stored item is served and
    graded alike, and :func:`app.services.answer_acceptance.widened_answers` takes its
    answer without the name as well."""

    if isinstance(node, list):
        return [unaddressed_payload(child) for child in node]
    if not isinstance(node, dict):
        return node
    if is_build_or_write(node):
        stripped = unaddressed_item(node)
        node = stripped if stripped is not None else node
    return {key: (value if key in _KEEP else unaddressed_payload(value)) for key, value in node.items()}


def unaddressed_generated(payload: dict[str, Any]) -> dict[str, Any]:
    """A model-generated set with every build/write item said to nobody; an item that
    is no sentence without its address is dropped when its list keeps another one."""

    def prune(node: Any) -> Any:
        if isinstance(node, dict):
            out = {key: (value if key in _KEEP else prune(value)) for key, value in node.items()}
            if isinstance(out.get("items"), list):
                kept = [item for item in out["items"] if not is_build_or_write(item) or unaddressed_item(item) is not None]
                if kept and len(kept) < len(out["items"]):
                    out["items"] = kept
            return out
        if isinstance(node, list):
            return [prune(child) for child in node]
        return node

    return unaddressed_payload(prune(payload))


#: Brief and error-repair exercise types the learner writes.
_WRITTEN_EXERCISES = frozenset({"translation", "correction", "rewrite", "short_answer"})


def unaddressed_exercise(exercise: Any) -> Any:
    """A model-written brief or error-repair exercise said to nobody: its
    ``correct_answer``, its ``prompt`` (an English sentence to translate, a French one to
    repair) and its ``instruction``/``hint`` lose the same address. ``exercise`` itself
    when it names nobody or would be no sentence without its address."""

    if not isinstance(exercise, dict):
        return exercise
    kind = exercise.get("type") or exercise.get("exercise_type")
    answer = exercise.get("correct_answer")
    if kind not in _WRITTEN_EXERCISES or not isinstance(answer, str):
        return exercise
    names = addressed_names(answer)
    if isinstance(exercise.get("prompt"), str) and kind in {"correction", "rewrite"}:
        names.extend(name for name in addressed_names(exercise["prompt"]) if name not in names)
    if not names:
        return exercise
    bare = strip_vocative(answer, names)
    if _letter_words(bare) < MIN_WORDS:
        return exercise
    out = dict(exercise, correct_answer=bare)
    for field in ("prompt", "instruction", "hint"):
        if isinstance(out.get(field), str):
            out[field] = strip_vocative(out[field], names)
    return out


