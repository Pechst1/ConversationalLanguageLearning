#: The recall formats the learner builds or writes. A dictation is heard and typed as
#: heard: no place to decide, so it keeps its line.
BUILD_WRITE_TASKS = frozenset({"tiles", "word_bank", "unscramble", "short_answer", "transform"})
_TU_VOUS = frozenset({"tu", "te", "toi", "ton", "ta", "tes", "vous", "votre", "vos", "t'"})


def _tile_text(option: dict[str, Any]) -> str:
    return str(option.get("text_fr") or option.get("text") or option.get("label") or "")


def _words(text: str) -> set[str]:
    return set(re.findall(r"\w+'?", text.casefold()))


def _swaps_register(task: Any) -> bool:
    """A repair between «tu» and «vous», whose address may be the only cue to the register
    («Monsieur, un café, s'il te plaît.»): without it the ✗ sentence is not wrong."""

    source = str(getattr(task, "source_fr", None) or getattr(task, "prompt_fr", None) or "")
    right = str(getattr(task, "solution_fr", None) or "")
    return bool((_words(source) ^ _words(right)) & _TU_VOUS)


def _retile(task: Any, names: list[str], sentence: str) -> Any | None:
    order = list(task.correct_tile_order or [])
    by_id = {str(option.get("id")): option for option in task.options or []}
    if not order or any(tile not in by_id for tile in order):
        return None
    texts = [_tile_text(by_id[tile]) for tile in order]
    from app.services.scene_items import tile_words

    attached = not any(text in {",", ".", "?", "!"} for text in texts)
    words = tile_words(sentence) if attached else re.findall(r"[^\s,.!?;:…]+|[,.!?;:…]", sentence)
    if not words:
        return None
    # Keep each tile whose word is still there, in order; make a new tile for a word that
    # changed («Lila,» → «Lila.»); drop the tiles of the address.
    tiles: list[dict[str, Any]] = []
    used: set[str] = set()
    cursor = 0
    for index, word in enumerate(words):
        match = next(
            (tile for tile in order[cursor:] if tile not in used and _tile_text(by_id[tile]) == word),
            None,
        )
        if match is not None:
            cursor = order.index(match) + 1
            used.add(match)
            tiles.append(by_id[match])
            continue
        base = by_id[order[min(cursor, len(order) - 1)]]
        digest = hashlib.sha256(f"{'|'.join(order)}|{index}|{word}".encode()).hexdigest()[:8]
        key = "text_fr" if "text_fr" in base else "text"
        tiles.append({**{k: v for k, v in base.items() if k not in {"id", key}}, "id": f"tile_{digest}", key: word})
    new_order = [str(tile["id"]) for tile in tiles]
    if len(set(new_order)) != len(new_order):
        return None
    dropped = set(order) - used
    replaced = iter(tile for tile in tiles if str(tile["id"]) not in by_id)
    options: list[dict[str, Any]] = []
    for option in task.options:
        tile = str(option.get("id"))
        if tile in dropped:
            # Where a changed tile stood, its new form stands; an address tile goes.
            new = next(replaced, None)
            if new is not None:
                options.append(new)
            continue
        options.append(option)
    options.extend(replaced)
    if not set(new_order) <= {str(option.get("id")) for option in options}:
        return None
    return replace(task, options=options, correct_tile_order=new_order)


def unaddressed_task(task: Any) -> Any | None:
    """A journey recall task said to nobody (owner decision 12 Nov 2026).

    The sentence the learner builds or writes, its accepted answers, its tiles and every
    line in the learner's language that quotes it lose the same address; ``task`` itself
    when it names nobody or is answered by choosing; ``None`` when what is left is no
    sentence, or the address was the only cue to the register a repair is about."""

    if str(getattr(task, "task_type", "")) not in BUILD_WRITE_TASKS:
        return task
    french = [task.solution_fr, task.prompt_fr, task.source_fr, *task.accepted_answers]
    tiles = task.task_type in {"tiles", "word_bank", "unscramble"}
    if tiles:
        by_id = {str(option.get("id")): option for option in task.options or []}
        french.append(" ".join(_tile_text(by_id[tile]) for tile in task.correct_tile_order if tile in by_id))
    names: list[str] = []
    for text in french:
        if isinstance(text, str):
            names.extend(name for name in addressed_names(text) if name not in names)
    if any(isinstance(text, str) and opens_on_a_person(strip_vocative(text, names) if names else text) for text in french):
        # «Gus, c'est la famille d'Odile.»: said to Gus or about him — not a build.
        return None
    if not names:
        return task
    if task.task_type == "transform" and _swaps_register(task):
        return None

    def bare(text: Any) -> Any:
        return strip_vocative(text, names) if isinstance(text, str) else text

    hint = bare(task.hint_native)
    if isinstance(hint, str) and any(re.search(rf"\b{re.escape(name)}\b", hint) for name in names):
        # «Der Satz beginnt mit «Lila».»: the first word it names is gone.
        hint = None

    accepted = list(dict.fromkeys(bare(answer) for answer in task.accepted_answers))
    solution = bare(task.solution_fr)
    key = solution or (accepted[0] if accepted else None)
    if not key or _letter_words(key) < MIN_WORDS or addressed_names(key):
        return None
    stripped = replace(
        task,
        prompt_fr=bare(task.prompt_fr),
        source_fr=bare(task.source_fr),
        solution_fr=solution,
        accepted_answers=accepted,
        goal_native=bare(task.goal_native),
        translation_native=bare(task.translation_native),
        hint_native=hint,
        instruction_native=bare(task.instruction_native),
    )
    if tiles:
        return _retile(stripped, names, key)
    return stripped
