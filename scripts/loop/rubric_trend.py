"""Each rubric question's score night by night, from the walk reports in docs/ops/walks/.

    python scripts/loop/rubric_trend.py            # print the table
    python scripts/loop/rubric_trend.py --write    # also write docs/ops/walks/TREND.md

Every report scores the 22 questions of docs/ops/walk-rubric.md in a table whose columns are
walks: tonight's personas and days, and earlier walks copied in for comparison («a1-de d1
14 Oct», «live 16 Oct (A1.1, day 5)»). A column is dated by the «DD Mon» in its header,
else by the report's own date, and a walk copied into several reports counts once. Fake-
provider walks (explore) and real-model walks (live walk, app walk on the Mac) are averaged
apart: the fake provider cannot judge Q4, and only live walks see production.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path
from statistics import mean

WALKS = Path(__file__).resolve().parents[2] / "docs" / "ops" / "walks"
REPORT = re.compile(r"^(\d{4})-(\d{2})-(\d{2})\.md$")
HEADER = re.compile(r"^\|\s*#\s*\|\s*question\s*\|")
DAY_MONTH = re.compile(r"\b(\d{1,2}) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\b")
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()
REAL_MODEL = re.compile(r"\b(live|app walk)\b", re.IGNORECASE)


def cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def column_walk(header: str, report_day: date) -> tuple[date, str, str]:
    """(walk date, kind, persona label without the date) for one score column."""
    found = DAY_MONTH.search(header)
    day = report_day
    if found:
        day = date(report_day.year, MONTHS.index(found.group(2)) + 1, int(found.group(1)))
    label = DAY_MONTH.sub("", header).strip()
    return day, "live" if REAL_MODEL.search(header) else "explore", label


def collect(walks: Path = WALKS) -> tuple[dict[int, str], dict[tuple[date, str], dict[int, list[float]]]]:
    """Question titles, and (date, kind) -> question -> scores, each walk counted once."""
    titles: dict[int, str] = {}
    scores: dict[tuple[date, str], dict[int, list[float]]] = defaultdict(lambda: defaultdict(list))
    seen: set[tuple[date, str]] = set()
    for path in sorted(walks.iterdir()):
        match = REPORT.match(path.name)
        if not match:
            continue
        report_day = date(*map(int, match.groups()))
        lines = path.read_text(encoding="utf-8").splitlines()
        start = next((i for i, line in enumerate(lines) if HEADER.match(line)), None)
        if start is None:
            continue
        columns = [column_walk(h, report_day) for h in cells(lines[start])[2:]]
        fresh = [(day, label) not in seen for day, _, label in columns]
        seen.update((day, label) for day, _, label in columns)
        for line in lines[start + 2:]:
            if not line.startswith("|"):
                break
            row = cells(line)
            if not row[0].isdigit():
                continue
            number = int(row[0])
            titles.setdefault(number, row[1])
            for (day, kind, _), is_new, value in zip(columns, fresh, row[2:], strict=False):
                if is_new and re.fullmatch(r"[1-5](\.\d)?", value):
                    scores[(day, kind)][number].append(float(value))
    return titles, scores


def table(titles: dict[int, str], scores: dict[tuple[date, str], dict[int, list[float]]]) -> str:
    keys = sorted(scores)
    head = ["#", "question"] + [f"{d.day} {MONTHS[d.month - 1]} {'live' if k == 'live' else 'fake'}" for d, k in keys]
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for number in sorted(titles):
        row = [str(number), titles[number]]
        for key in keys:
            values = scores[key].get(number)
            row.append(f"{mean(values):.1f}".rstrip("0").rstrip(".") if values else "")
        out.append("| " + " | ".join(row) + " |")
    return "\n".join(out)


def main(argv: list[str]) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="write docs/ops/walks/TREND.md")
    args = parser.parse_args(argv)
    titles, scores = collect()
    text = table(titles, scores)
    print(text)
    if args.write:
        (WALKS / "TREND.md").write_text(
            "# Rubric trend\n\n"
            "Generated by `python scripts/loop/rubric_trend.py --write` from the walk reports in this "
            "folder; do not edit by hand. Each cell is the mean score (1 to 5) of the walks that night: "
            "«fake» columns are explore walks on the fake provider, «live» columns are walks against the "
            "real model (live walk, app walk). Questions: `docs/ops/walk-rubric.md`. A fix should move "
            "its question up; a drop is a regression no assertion caught.\n\n" + text + "\n",
            encoding="utf-8",
        )


if __name__ == "__main__":
    main(sys.argv[1:])
