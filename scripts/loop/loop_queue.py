"""The improvement loop's work queue, kept in GitHub issue labels.

The walks file `walk-finding` issues; triage gives each one a state, a lane and a size;
the night shift claims `queue:ready` issues, fixes them on their own branches and opens
PRs; `merge-ready` lists the small code fixes whose checks are all green (the owner merges
them, by hand or with `--merge`); `digest` writes the morning summary. See
docs/ops/improvement-loop.md.

    python scripts/loop/loop_queue.py ensure-labels
    python scripts/loop/loop_queue.py ready [--lane code|story] [--limit N]
    python scripts/loop/loop_queue.py claim N --run RUN
    python scripts/loop/loop_queue.py release N --reason TEXT
    python scripts/loop/loop_queue.py mark-pr N --pr PR
    python scripts/loop/loop_queue.py merge-ready [--merge] [--max N]
    python scripts/loop/loop_queue.py digest --date YYYY-MM-DD

The night shift's GitHub verbs (it has no other way to read or write issues and PRs):

    python scripts/loop/loop_queue.py show N              # issue or PR body and every comment
    python scripts/loop/loop_queue.py open-night-prs      # count of open claude/night-* PRs
    python scripts/loop/loop_queue.py pr-create --branch B --title T --body-file F [--label L]... [--draft]
    python scripts/loop/loop_queue.py pr-diff N
    python scripts/loop/loop_queue.py comment N --body-file F    (or --body TEXT)
    python scripts/loop/loop_queue.py pr-unready N --body-file F # drop loop:merge-ready, draft, say why

Everything goes through GitHub's REST API with `gh api` (cloud sessions block GraphQL,
so `gh issue`/`gh pr` fail there). With the owner's login, a merge made with `--merge`
starts CI on main like any other push (a merge by the Actions token would not, and
Render deploys only once main's checks pass). The night shift itself only lists.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Any
from urllib.parse import quote

REPO = os.environ.get("LOOP_REPO", "Pechst1/ConversationalLanguageLearning")

# name -> (colour, description)
LABELS: dict[str, tuple[str, str]] = {
    "queue:ready": ("0e8a16", "Loop queue: reproduced, small, has a done-when check"),
    "queue:working": ("fbca04", "Loop queue: claimed by a night-shift agent"),
    "queue:pr": ("1d76db", "Loop queue: a PR that fixes it is open"),
    "queue:owner": ("d93f0b", "Loop queue: needs a product decision from the owner"),
    "lane:code": ("c5def5", "Fixed in UI/drill/API code; checked by tests and the scripted walk"),
    "lane:story": ("d4c5f9", "Fixed in the story engine; checked by a guard plus a test from the walk's exact text"),
    "size:S": ("ededed", "One focused change, a few files"),
    "size:M": ("bfbfbf", "Several files or one subsystem"),
    "loop:merge-ready": ("0e8a16", "Small code fix the owner may merge as soon as every check is green"),
    "needs-owner-review": ("b60205", "PR changes story behaviour or product copy: owner merges"),
}
STATE_LABELS = ("queue:ready", "queue:working", "queue:pr", "queue:owner")
SEVERITY_ORDER = {"sev:blocker": 0, "sev:high": 1, "sev:medium": 2, "sev:low": 3}

# A PR is listed as ready to merge only when it touches none of these. Story engine, data model,
# deploy and the loop's own rules always wait for the owner.
MERGE_DENY_PREFIXES = (
    ".github/",
    ".claude/",
    "alembic/",
    "app/core/",
    "app/db/",
    "app/services/season/",
    "app/services/living_story",
    "app/services/journey_conversation",
    "scripts/loop/",
    "docs/ops/improvement-loop.md",
    "render.yaml",
    "Dockerfile",
    "docker-compose",
    "requirements",
    "pyproject.toml",
    "web-frontend/package.json",
    "web-frontend/package-lock.json",
    "ios/",
)
MERGE_MAX_LINES = 400
MERGE_MIN_CHECKS = 5
CHECK_OK = {"SUCCESS", "SKIPPED", "NEUTRAL"}
NIGHT_BRANCH = "claude/night-"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def api(method: str, path: str, body: Any = None, accept: str | None = None) -> str:
    """One REST call through `gh api`; `path` is relative to the repo unless it starts with /."""
    url = path if path.startswith("/") else f"/repos/{REPO}/{path}"
    argv = ["gh", "api", "-X", method, url]
    if accept:
        argv += ["-H", f"Accept: {accept}"]
    if body is not None:
        argv += ["--input", "-"]
    result = subprocess.run(  # noqa: S603 - fixed gh argv, no shell
        argv, capture_output=True, text=True, check=False,
        input=json.dumps(body) if body is not None else None,
    )
    if result.returncode != 0:
        raise SystemExit(f"gh api {method} {url} failed: {(result.stderr or result.stdout).strip()}")
    return result.stdout


def api_json(method: str, path: str, body: Any = None) -> Any:
    return json.loads(api(method, path, body) or "null")


def api_list(path: str, limit: int = 1000) -> list[dict[str, Any]]:
    """GET every page of a list endpoint (100 per page) up to `limit` items."""
    items: list[dict[str, Any]] = []
    sep = "&" if "?" in path else "?"
    page = 1
    while len(items) < limit:
        batch = api_json("GET", f"{path}{sep}per_page=100&page={page}")
        if isinstance(batch, dict):  # e.g. check-runs wraps its list
            batch = next((v for v in batch.values() if isinstance(v, list)), [])
        items += batch
        if len(batch) < 100:
            break
        page += 1
    return items[:limit]


def label_names(item: dict[str, Any]) -> set[str]:
    return {label["name"] for label in item.get("labels", [])}


def add_labels(number: int, names: list[str]) -> None:
    if names:
        api("POST", f"issues/{number}/labels", {"labels": names})


def remove_label(number: int, name: str) -> None:
    """Remove one label; a label that is not there is fine."""
    try:
        api("DELETE", f"issues/{number}/labels/{quote(name, safe='')}")
    except SystemExit as exc:
        if "404" not in str(exc) and "Label does not exist" not in str(exc):
            raise


def comment(number: int, text: str) -> None:
    if not text.rstrip().endswith("_Generated by [Claude Code](https://claude.ai/code)_"):
        text = text.rstrip() + FOOTER
    api("POST", f"issues/{number}/comments", {"body": text})


def set_state(number: int, state: str) -> None:
    """Move an issue to one queue state, removing the others."""
    current = label_names(api_json("GET", f"issues/{number}"))
    add_labels(number, [state])
    for name in STATE_LABELS:
        if name != state and name in current:
            remove_label(number, name)


def ensure_labels() -> None:
    existing = {item["name"] for item in api_list("labels")}
    for name, (colour, description) in LABELS.items():
        if name not in existing:
            api("POST", "labels", {"name": name, "color": colour, "description": description})
            print(f"created {name}")


def open_issues(*labels: str) -> list[dict[str, Any]]:
    """Open issues (never PRs) carrying every one of `labels`."""
    query = "issues?state=open"
    if labels:
        query += "&labels=" + quote(",".join(labels), safe=",")
    return [i for i in api_list(query) if "pull_request" not in i]


def ready_issues(lane: str | None, limit: int) -> list[dict[str, Any]]:
    issues = open_issues("queue:ready", *([f"lane:{lane}"] if lane else []))

    def rank(issue: dict[str, Any]) -> tuple[int, int, str]:
        names = label_names(issue)
        severity = min((SEVERITY_ORDER[n] for n in names if n in SEVERITY_ORDER), default=2)
        size = 0 if "size:S" in names else 1
        return (severity, size, issue["created_at"])

    issues.sort(key=rank)
    return [
        {
            "number": issue["number"],
            "title": issue["title"],
            "url": issue["html_url"],
            "labels": sorted(label_names(issue)),
        }
        for issue in issues[:limit]
    ]


def claim(number: int, run: str) -> None:
    issue = api_json("GET", f"issues/{number}")
    if issue["state"] != "open" or "queue:ready" not in label_names(issue):
        raise SystemExit(f"#{number} is not queue:ready; not claimed")
    set_state(number, "queue:working")
    comment(number, f"Night shift {run}: working on this.")


def release(number: int, reason: str) -> None:
    set_state(number, "queue:ready")
    comment(number, f"Night shift gave this back to the queue: {reason}")


def mark_pr(number: int, pr: int) -> None:
    set_state(number, "queue:pr")
    comment(number, f"Fix proposed in #{pr}.")


def show(number: int) -> str:
    """An issue or PR as text: title, labels, body, then every comment in order."""
    issue = api_json("GET", f"issues/{number}")
    out = [f"#{number} {issue['title']} [{issue['state']}]",
           "labels: " + ", ".join(sorted(label_names(issue))), "", issue.get("body") or ""]
    for c in api_list(f"issues/{number}/comments"):
        out += ["", f"--- {c['user']['login']} · {c['created_at']}", c["body"]]
    return "\n".join(out)


def night_prs(state: str = "open") -> list[dict[str, Any]]:
    return [p for p in api_list(f"pulls?state={state}&sort=created&direction=desc", limit=300)
            if p["head"]["ref"].startswith(NIGHT_BRANCH)]


def pr_create(branch: str, title: str, body: str, labels: list[str], draft: bool) -> int:
    pr = api_json("POST", "pulls", {"title": title, "head": branch, "base": "main",
                                    "body": body, "draft": draft})
    add_labels(pr["number"], labels)
    print(pr["html_url"])
    return pr["number"]


def pr_unready(number: int, reason: str) -> None:
    """Verifier verdict 'not ok': no merge-ready label, back to draft, and why."""
    remove_label(number, "loop:merge-ready")
    try:
        api("POST", f"pulls/{number}/ccr/convert_to_draft")
    except SystemExit as exc:  # outside a Claude Code session the route does not exist
        print(f"could not convert #{number} to draft: {exc}", file=sys.stderr)
    comment(number, reason)


def pr_rollup(number: int) -> dict[str, Any]:
    """A PR in the shape merge_blockers reads (the field names of `gh pr view --json`)."""
    pr = api_json("GET", f"pulls/{number}")
    sha = pr["head"]["sha"]
    checks: list[dict[str, Any]] = [
        {"__typename": "CheckRun", "name": run["name"], "status": (run["status"] or "").upper(),
         "conclusion": (run["conclusion"] or "").upper() or None}
        for run in api_list(f"commits/{sha}/check-runs")
    ]
    statuses = api_json("GET", f"commits/{sha}/status").get("statuses", [])
    checks += [{"__typename": "StatusContext", "context": s["context"], "state": s["state"].upper()}
               for s in statuses]
    mergeable = {True: "MERGEABLE", False: "CONFLICTING"}.get(pr.get("mergeable"), "UNKNOWN")
    return {
        "number": pr["number"],
        "title": pr["title"],
        "state": "MERGED" if pr.get("merged_at") else pr["state"].upper(),
        "isDraft": pr.get("draft", False),
        "labels": pr.get("labels", []),
        "headRefName": pr["head"]["ref"],
        "mergeable": mergeable,
        "additions": pr.get("additions", 0),
        "deletions": pr.get("deletions", 0),
        "files": [{"path": f["filename"]} for f in api_list(f"pulls/{number}/files")],
        "statusCheckRollup": checks,
    }


def merge_blockers(pr: dict[str, Any]) -> list[str]:
    """Why this PR is not ready to merge; empty means it is."""
    blockers: list[str] = []
    names = label_names(pr)
    if pr.get("state") != "OPEN":
        blockers.append("not open")
    if pr.get("isDraft"):
        blockers.append("draft")
    if "loop:merge-ready" not in names:
        blockers.append("no loop:merge-ready label")
    if "needs-owner-review" in names:
        blockers.append("needs-owner-review")
    if not pr.get("headRefName", "").startswith("claude/night-"):
        blockers.append("not a night-shift branch")
    if pr.get("mergeable") != "MERGEABLE":
        blockers.append(f"mergeable={pr.get('mergeable')}")
    lines = int(pr.get("additions", 0)) + int(pr.get("deletions", 0))
    if lines > MERGE_MAX_LINES:
        blockers.append(f"{lines} changed lines > {MERGE_MAX_LINES}")
    denied = [f["path"] for f in pr.get("files", []) if f["path"].startswith(MERGE_DENY_PREFIXES)]
    if denied:
        blockers.append("touches owner-only paths: " + ", ".join(sorted(denied)[:5]))
    checks = pr.get("statusCheckRollup") or []
    if len(checks) < MERGE_MIN_CHECKS:
        blockers.append(f"only {len(checks)} checks reported")
    for check in checks:
        name = check.get("name") or check.get("context") or "?"
        if check.get("__typename") == "StatusContext":
            if check.get("state") != "SUCCESS":
                blockers.append(f"{name}: {check.get('state')}")
        elif check.get("status") != "COMPLETED":
            blockers.append(f"{name}: still running")
        elif check.get("conclusion") not in CHECK_OK:
            blockers.append(f"{name}: {check.get('conclusion')}")
    return blockers


def merge_ready(limit: int, merge: bool) -> None:
    prs = [p for p in api_list("pulls?state=open") if "loop:merge-ready" in label_names(p)]
    merged = 0
    for item in prs:
        if merged >= limit:
            print(f"cap {limit} reached; the rest wait for the next run")
            break
        pr = pr_rollup(item["number"])
        blockers = merge_blockers(pr)
        if blockers:
            print(f"#{pr['number']} waits: {'; '.join(blockers)}")
            continue
        if merge:
            api("PUT", f"pulls/{pr['number']}/merge", {"merge_method": "squash"})
            api("DELETE", f"git/refs/heads/{pr['headRefName']}")
            print(f"#{pr['number']} merged: {pr['title']}")
        else:
            print(f"#{pr['number']} ready to merge: {pr['title']}")
        merged += 1


def digest(date: str) -> str:
    ready, working, owner = open_issues("queue:ready"), open_issues("queue:working"), open_issues("queue:owner")
    prs = [p for p in night_prs("all") if p["created_at"][:10] >= date]
    lines = [f"## Night shift · {date}", ""]
    lines.append(f"Queue: {len(ready)} ready · {len(working)} in work · {len(owner)} waiting for you")
    lines.append("")
    if prs:
        lines.append("| PR | state | lane | title |")
        lines.append("|---|---|---|---|")
        for pr in prs:
            names = label_names(pr)
            state = "merged" if pr.get("merged_at") else "draft" if pr.get("draft") else pr["state"]
            lane = "story" if "needs-owner-review" in names else "code"
            auto = " · auto" if "loop:merge-ready" in names else ""
            lines.append(f"| #{pr['number']} | {state}{auto} | {lane} | {pr['title']} |")
    else:
        lines.append("No night-shift PRs tonight.")
    if working:
        lines += ["", "Still claimed (an agent may have stopped): "
                  + ", ".join(f"#{i['number']}" for i in working)]
    if owner:
        lines += ["", "Waiting for your decision:"]
        lines += [f"- #{i['number']} {i['title']}" for i in owner[:15]]
    return "\n".join(lines)


def _text(args: argparse.Namespace) -> str:
    if getattr(args, "body_file", None):
        return Path(args.body_file).read_text(encoding="utf-8")
    if getattr(args, "body", None):
        return args.body
    raise SystemExit("give --body or --body-file")


def main(argv: list[str]) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("ensure-labels")
    p = sub.add_parser("ready")
    p.add_argument("--lane", choices=["code", "story"])
    p.add_argument("--limit", type=int, default=50)
    p = sub.add_parser("claim")
    p.add_argument("number", type=int)
    p.add_argument("--run", required=True)
    p = sub.add_parser("release")
    p.add_argument("number", type=int)
    p.add_argument("--reason", required=True)
    p = sub.add_parser("mark-pr")
    p.add_argument("number", type=int)
    p.add_argument("--pr", type=int, required=True)
    p = sub.add_parser("merge-ready")
    p.add_argument("--max", type=int, default=4)
    p.add_argument("--merge", action="store_true", help="merge them (owner only); default lists")
    p = sub.add_parser("digest")
    p.add_argument("--date", required=True)
    p = sub.add_parser("show")
    p.add_argument("number", type=int)
    sub.add_parser("open-night-prs")
    p = sub.add_parser("pr-create")
    p.add_argument("--branch", required=True)
    p.add_argument("--title", required=True)
    p.add_argument("--body-file")
    p.add_argument("--body")
    p.add_argument("--label", action="append", default=[])
    p.add_argument("--draft", action="store_true")
    p = sub.add_parser("pr-diff")
    p.add_argument("number", type=int)
    for name in ("comment", "pr-unready"):
        p = sub.add_parser(name)
        p.add_argument("number", type=int)
        p.add_argument("--body-file")
        p.add_argument("--body")
    args = parser.parse_args(argv)

    if args.command == "ensure-labels":
        ensure_labels()
    elif args.command == "ready":
        print(json.dumps(ready_issues(args.lane, args.limit), indent=1, ensure_ascii=False))
    elif args.command == "claim":
        claim(args.number, args.run)
    elif args.command == "release":
        release(args.number, args.reason)
    elif args.command == "mark-pr":
        mark_pr(args.number, args.pr)
    elif args.command == "merge-ready":
        merge_ready(args.max, args.merge)
    elif args.command == "digest":
        print(digest(args.date))
    elif args.command == "show":
        print(show(args.number))
    elif args.command == "open-night-prs":
        print(len(night_prs("open")))
    elif args.command == "pr-create":
        pr_create(args.branch, args.title, _text(args), args.label, args.draft)
    elif args.command == "pr-diff":
        print(api("GET", f"pulls/{args.number}", accept="application/vnd.github.diff"))
    elif args.command == "comment":
        comment(args.number, _text(args))
    elif args.command == "pr-unready":
        pr_unready(args.number, _text(args))


if __name__ == "__main__":
    main(sys.argv[1:])
