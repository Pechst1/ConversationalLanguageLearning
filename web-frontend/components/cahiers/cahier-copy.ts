const TABLES: Record<ControlLanguage, CahierCopy> = { en: EN, de: DE, fr: FR };

/** The Cahier copy table for a chrome language (regional tags and nulls normalised). */
export function cahierCopy(language: unknown): CahierCopy {
  return TABLES[normalizeControlLanguage(language)];
}

/** The copy table of the surrounding `AtelierV2Root` (its `language` prop). */
export function useCahierCopy(): CahierCopy {
  return cahierCopy(useControlLanguage());
}

/** `{n}`-style placeholders filled in. */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
}

/** «3 fiches», «1 fiche»: the `_one` / `_many` pair of a group, with `{n}` filled. */
export function countLabel<G extends Record<string, string>>(
  group: G,
  stem: string,
  n: number,
): string {
  const key = `${stem}_${n === 1 ? 'one' : 'many'}`;
  const template = group[key];
  return typeof template === 'string' ? fill(template, { n }) : String(n);
}
