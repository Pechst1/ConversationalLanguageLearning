/**
 * WP-82 — Le Cahier follows the one language rule.
 *
 * The Cahier's own words — tab labels, filters, counts, section heads, the
 * notes bar, the journal's instructions and verdicts, the library runner, the
 * word biography's ledger, the fragility chip — are chrome: up to A2 they are
 * the learner's language, from B1 they are French (`chromeLanguage`,
 * `lib/language-rule.ts`). What arrives from the server as learner material
 * (a rule, an example, a trap, a scene, the learner's own text, a concept's
 * French title and category) is content and stays French whatever this table
 * says. Place names (Le Cahier, Relevé, Bibliothèque, Lexique, L’Atelier, Le
 * Feuilleton, Le Courrier, Le Studio, L’Épreuve) are French in every column.
 *
 * One module for the whole cluster, grouped by screen: `cahier` (the shared
 * head and pill in CahierV2), `notes` (the margin notes, shared by the grammar
 * fiche and the legacy Cahiers kit), `grammar`, `notebook` (the /notebook
 * shell), `library`, `journal`, `legacy` (components/cahiers/Cahiers.tsx),
 * `biography` (the word biography sheet) and `fragility` (the badge).
 *
 * Every table has the same keys and the same `{placeholders}` (the copy test
 * proves it). The French column keeps the wording these screens always had.
 */

