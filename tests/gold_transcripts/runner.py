def criterion_of(surface: str, key: str) -> str:
    """The criterion a verdict is about: a day keeps its verdicts per act
    (``<role>.<criterion>``), every other surface by the criterion alone."""

    return key.partition(".")[2] if surface == DAY_SURFACE else key


def act_scores(verdicts: dict[str, tuple[str, str]]) -> dict[str, float | None]:
    """A day's score per act: a written act's page score over the questions asked of it
    (an unrated question earns nothing), a dropped act or a lost page 0."""

    by_act: dict[str, dict[str, tuple[str, str]]] = {}
    for key, verdict in verdicts.items():
        role, _, criterion = key.partition(".")
        by_act.setdefault(role, {})[criterion] = verdict
    scores: dict[str, float | None] = {}
    for role, mine in by_act.items():
        if (mine.get("served") or ("pass", ""))[0] == "fail":
            scores[role] = 0.0
            continue
        asked = [key for key in mine if key != "served"]
        ratings = page_ratings({key: mine[key] for key in asked})
        scores[role] = sum((ratings[k] - 1) / 4 if k in ratings else 0.0 for k in asked) / len(asked) if asked else None
    return scores


def item_score(verdicts: dict[str, tuple[str, str]], surface: str | None = None) -> float | None:
    if surface == DAY_SURFACE:
        scores = [value for value in act_scores(verdicts).values() if value is not None]
        return sum(scores) / len(scores) if scores else None
    if surface == "page":
        # Every asked question counts: one the judge left unrated earns nothing.
        asked = [c.id for c in judged("page") if c.id in verdicts]
        ratings = page_ratings(verdicts)
        if asked:
            return sum((ratings[key] - 1) / 4 if key in ratings else 0.0 for key in asked) / len(asked)
    counted = [v for v, _ in verdicts.values() if v in {"pass", "fail"}]
    return (sum(1 for v in counted if v == "pass") / len(counted)) if counted else None


def summarize(surface: str, rows: list[dict]) -> dict:
    run = [row for row in rows if row["status"] == "scored"]
    scores = [row["score"] for row in run if row["score"] is not None]
    # A day's verdicts are kept per act (``<role>.<criterion>``).
    keys = (
        sorted({key for row in run for key in row["verdicts"]})
        if surface == DAY_SURFACE
        else [criterion.id for criterion in CRITERIA[surface]]
    )
    per_criterion: dict[str, str] = {}
    for key in keys:
        marks = [row["verdicts"].get(key, ("na", ""))[0] for row in run]
        counted = [m for m in marks if m in {"pass", "fail"}]
        if counted:
            per_criterion[key] = f"{sum(1 for m in counted if m == 'pass')}/{len(counted)}"
    summary = {
        "score": round(100 * sum(scores) / len(scores), 1) if scores else None,
        "items": len(rows),
        "scored": len(run),
        "not_run": len(rows) - len(run),
        "failed_outright": sum(1 for row in run if row.get("failure")),
        "criteria": per_criterion,
    }
    if surface == DAY_SURFACE:
        summary.update(days=[row["id"] for row in run], acts=day_acts(run))
    if surface == "page":
        seconds = sorted(float((row.get("output") or {}).get("seconds") or 0) for row in run)
        ratings: dict[str, list[int]] = {}
        for row in run:
            for key, value in page_ratings(row.get("verdicts") or {}).items():
                ratings.setdefault(key, []).append(value)
        summary.update(
            seconds_median=round(statistics.median(seconds), 1) if seconds else None,
            seconds_max=seconds[-1] if seconds else None,
            lost=summary["failed_outright"],
            ratings={key: {"mean": round(statistics.mean(v), 2), "median": statistics.median(v)} for key, v in ratings.items()},
        )
    return summary


def day_acts(rows: list[dict]) -> dict[str, dict]:
    """Per act of the days run, in play order: how many were written, dropped (or the day
    lost) and left unwritten by the cap, their seconds and cost, their ratings, the story
    judge's gate on the act alone, and its mean rating against «Le fil»'s."""

    from app.services.journey_contracts import ACT_ROLE_ORDER
    from app.services.season import story_judge as SJ

    acts: dict[str, dict] = {}
    for role in (str(role) for role in ACT_ROLE_ORDER):
        written = dropped = not_run = 0
        seconds: list[float] = []
        cost: list[float] = []
        why: list[str] = []
        unwritten: list[str] = []
        places: list[str] = []
        ratings: dict[str, list[int]] = {}
        for row in rows:
            act = next((a for a in (row.get("output") or {}).get("acts") or [] if a.get("role") == role), None)
            if act is None:
                continue
            if act.get("not_run"):
                not_run += 1
                unwritten.append(str(act["not_run"]))
                continue
            seconds.append(float(act.get("seconds") or 0.0))
            cost.append(float(act.get("cost_usd") or 0.0))
            if act.get("failure"):
                dropped += 1
                why.append(S.compact(act["failure"], 120))
                continue
            written += 1
            places.append(f"{act.get('lead')} · {act.get('place')}")
            mine = {key.split(".", 1)[1]: value for key, value in (row.get("verdicts") or {}).items() if key.startswith(f"{role}.")}
            for key, value in page_ratings(mine).items():
                ratings.setdefault(key, []).append(value)
        if not (written or dropped or not_run):
            continue
        table = {
            key: {"median": statistics.median(values), "count": len(values), "scores": values}
            for key, values in ratings.items()
        }
        acts[role] = {
            "label": SJ.ACT_LABELS.get(role, role),
            "written": written, "dropped": dropped, "not_run": not_run, "why": why, "unwritten": unwritten,
            "lead_place": places,
            "seconds": round(statistics.median(seconds), 1) if seconds else None,
            "cost_usd": round(sum(cost), 4),
            "ratings": {key: {"mean": round(statistics.mean(v), 2), "median": statistics.median(v)} for key, v in ratings.items()},
            "gate": SJ.gate(table)["verdict"] if table else None,
        }
    first = (acts.get("fil") or {}).get("ratings") or {}
    for role, act in acts.items():
        shared = [key for key in act["ratings"] if key in first]
        if role != "fil" and shared:
            act["vs_first"] = round(
                statistics.mean(act["ratings"][key]["mean"] for key in shared)
                - statistics.mean(first[key]["mean"] for key in shared), 2,
            )
    return acts


def week_day(items: list[dict], when: Date) -> list[dict]:
    """The day of the set a weekly run writes: one a week, in turn by ISO week."""

    return [items[when.isocalendar().week % len(items)]] if items else []


def set_version(surface: str) -> str:
    return hashlib.sha256((S.SETS / f"{surface}.json").read_bytes()).hexdigest()[:12]


def run(
    surfaces: list[str],
    *,
    client: Any,
    judge_client: Any | None = None,
    judge_model: str | None = None,
    limit: int | None = None,
    ids: list[str] | None = None,
    progress: Callable[[str], None] | None = None,
    when: Date | None = None,
) -> dict:
    """Run every item, round-robin across the surfaces (a cap reached late costs every
    surface alike), and score it. ``client`` is the meter (or a fake); the judge is
    :func:`judge_for` the surfaces unless named. The day surface writes one day a week
    (:func:`week_day` of ``when``) unless ``ids`` names days."""

    judge_client = judge_client or client
    judge_model = judge_for(surfaces, judge_model)
    queues = {}
    for surface in surfaces:
        items = S.load_items(surface, ids)
        if surface == DAY_SURFACE and not ids:
            items = week_day(items, when or Date.today())
        queues[surface] = items[: limit or None]
    rows: dict[str, list[dict]] = {s: [] for s in surfaces}
    order = []
    for index in range(max((len(q) for q in queues.values()), default=0)):
        order += [(s, queues[s][index]) for s in surfaces if index < len(queues[s])]
    for surface, item in order:
        row: dict[str, Any] = {"id": item["id"], "learner_text": item["learner_text"]}
        if getattr(client, "exhausted", False):
            row.update(status="not_run", reason="spending cap reached")
            rows[surface].append(row)
            continue
        if hasattr(client, "role"):
            client.role = "app"
        try:
            output = S.SURFACES[surface](item, client)
        except Exception as exc:  # noqa: BLE001 - one crashing item must not stop the run
            output = {"failure": f"crash: {type(exc).__name__}: {S.compact(exc, 200)}"}
        if getattr(client, "exhausted", False):
            row.update(status="not_run", reason="spending cap reached during the app's own call", output=output)
            rows[surface].append(row)
            continue
        verdicts = dict(S.checks(surface, item, output))
        row["output"] = output
        row["failure"] = output.get("failure")
        if output.get("failure"):
            # The learner saw a fallback: the item scores 0 and the judge is not paid for.
            row.update(status="scored", verdicts=verdicts, score=0.0)
            rows[surface].append(row)
            if progress:
                progress(f"{surface} {item['id']}: failed ({output['failure']})")
            continue
        if hasattr(judge_client, "role"):
            judge_client.role = "judge"
        try:
            verdicts.update(judge_item(judge_client, surface, item, output, model=judge_model))
        except BudgetExhausted:
            # What was written stays in the results: a day of acts is the dear part of a run.
            row.update(status="not_run", reason="spending cap reached before the judge", output=output)
            rows[surface].append(row)
            continue
        except Exception as exc:  # noqa: BLE001
            row.update(status="not_run", reason=f"judge failed: {S.compact(exc, 160)}", output=output)
            rows[surface].append(row)
            continue
        row.update(status="scored", verdicts=verdicts, score=item_score(verdicts, surface))
        rows[surface].append(row)
        if progress:
            progress(f"{surface} {item['id']}: {row['score'] if row['score'] is None else round(row['score'] * 100)}")
    return {
        "criteria_version": run_version(surfaces),
        "set_versions": {s: set_version(s) for s in surfaces},
        "judge_model": judge_model,
        "surfaces": {s: summarize(s, rows[s]) for s in surfaces},
        "items": rows,
    }


def rejudge(
    result: dict, *, judge_client: Any, judge_model: str, progress: Callable[[str], None] | None = None
) -> dict:
    """The same app answers scored by another judge: every judged item of ``result`` is
    asked again, the deterministic checks (a day's for each act, a dropped one's too) and
    the fallbacks stay as they were. This is how a judge change is calibrated before it
    replaces the old one."""

    rows_out: dict[str, list[dict]] = {}
    for surface, rows in result["items"].items():
        items = {item["id"]: item for item in S.load_items(surface)}
        checked = {c.id for c in CRITERIA[surface] if c.by == "check"}
        rows_out[surface] = []
        for row in rows:
            row = dict(row)
            item = items.get(row["id"])
            if row["status"] != "scored" or row.get("failure") or item is None or "output" not in row:
                rows_out[surface].append(row)
                continue
            if getattr(judge_client, "exhausted", False):
                row.update(status="not_run", reason="spending cap reached")
                rows_out[surface].append(row)
                continue
            verdicts = {key: tuple(v) for key, v in row["verdicts"].items() if criterion_of(surface, key) in checked}
            try:
                verdicts.update(judge_item(judge_client, surface, item, row["output"], model=judge_model))
            except Exception as exc:  # noqa: BLE001 - one failed judgement must not stop the rest
                row.update(status="not_run", reason=f"judge failed: {S.compact(exc, 160)}")
                rows_out[surface].append(row)
                continue
            row.update(verdicts=verdicts, score=item_score(verdicts, surface))
            rows_out[surface].append(row)
            if progress:
                progress(f"{surface} {row['id']}: {row['score'] if row['score'] is None else round(row['score'] * 100)}")
    out = dict(result)
    out.update(
        judge_model=judge_model, rejudged_from=result.get("judge_model"),
        surfaces={s: summarize(s, rows_out[s]) for s in rows_out}, items=rows_out,
    )
    return out


def judge_agreement(a: dict, b: dict) -> dict[str, dict]:
    """Per surface: both scores and how often the two judges gave the same verdict on
    the same judged criterion of the same answer (pass/fail/na); on a day, of the same act."""

    report: dict[str, dict] = {}
    for surface, rows_a in a["items"].items():
        rows_b = {row["id"]: row for row in b["items"].get(surface, [])}
        asked = [criterion.id for criterion in judged(surface)]
        same = total = 0
        flips: list[str] = []
        for row in rows_a:
            other = rows_b.get(row["id"])
            if not other or row["status"] != "scored" or other["status"] != "scored" or row.get("failure"):
                continue
            # A day's questions are asked of each act it wrote, in play order.
            keys = asked if surface != DAY_SURFACE else list(dict.fromkeys(
                key for key in (*row["verdicts"], *other["verdicts"]) if criterion_of(surface, key) in asked
            ))
            for key in keys:
                va = (row["verdicts"].get(key) or ("na", ""))[0]
                vb = (other["verdicts"].get(key) or ("na", ""))[0]
                total += 1
                if va == vb:
                    same += 1
                else:
                    flips.append(f"{row['id']} {key}: {va}→{vb}")
        report[surface] = {
            "score_a": a["surfaces"][surface]["score"], "score_b": b["surfaces"][surface]["score"],
            "agreement": round(same / total, 3) if total else None, "verdicts": total, "flips": flips,
        }
    return report


