def item_score(verdicts: dict[str, tuple[str, str]], surface: str | None = None) -> float | None:
    if surface == "page":
        # Every asked question counts: one the judge left unrated earns nothing.
        asked = [c.id for c in judged("page") if c.id in verdicts]
        ratings = page_ratings(verdicts)
        if asked:
            return sum((ratings[key] - 1) / 4 if key in ratings else 0.0 for key in asked) / len(asked)
    counted = [v for v, _ in verdicts.values() if v in {"pass", "fail"}]
    return (sum(1 for v in counted if v == "pass") / len(counted)) if counted else None


def summarize(surface: str, rows: list[dict]) -> dict:
    run = [row for row in rows if row["status"] == "scored"]
    scores = [row["score"] for row in run if row["score"] is not None]
    per_criterion: dict[str, str] = {}
    for criterion in CRITERIA[surface]:
        marks = [row["verdicts"].get(criterion.id, ("na", ""))[0] for row in run]
        counted = [m for m in marks if m in {"pass", "fail"}]
        if counted:
            per_criterion[criterion.id] = f"{sum(1 for m in counted if m == 'pass')}/{len(counted)}"
    summary = {
        "score": round(100 * sum(scores) / len(scores), 1) if scores else None,
        "items": len(rows),
        "scored": len(run),
        "not_run": len(rows) - len(run),
        "failed_outright": sum(1 for row in run if row.get("failure")),
        "criteria": per_criterion,
    }
    if surface == "page":
        seconds = sorted(float((row.get("output") or {}).get("seconds") or 0) for row in run)
        ratings: dict[str, list[int]] = {}
        for row in run:
            for key, value in page_ratings(row.get("verdicts") or {}).items():
                ratings.setdefault(key, []).append(value)
        summary.update(
            seconds_median=round(statistics.median(seconds), 1) if seconds else None,
            seconds_max=seconds[-1] if seconds else None,
            lost=summary["failed_outright"],
            ratings={key: {"mean": round(statistics.mean(v), 2), "median": statistics.median(v)} for key, v in ratings.items()},
        )
    return summary


def set_version(surface: str) -> str:
    return hashlib.sha256((S.SETS / f"{surface}.json").read_bytes()).hexdigest()[:12]


def run(
    surfaces: list[str],
    *,
    client: Any,
    judge_client: Any | None = None,
    judge_model: str = DEFAULT_JUDGE,
    limit: int | None = None,
    ids: list[str] | None = None,
    progress: Callable[[str], None] | None = None,
) -> dict:
    """Run every item, round-robin across the surfaces (a cap reached late costs every
    surface alike), and score it. ``client`` is the meter (or a fake)."""

    judge_client = judge_client or client
    queues = {s: S.load_items(s, ids)[: limit or None] for s in surfaces}
    rows: dict[str, list[dict]] = {s: [] for s in surfaces}
    order = []
    for index in range(max((len(q) for q in queues.values()), default=0)):
        order += [(s, queues[s][index]) for s in surfaces if index < len(queues[s])]
    for surface, item in order:
        row: dict[str, Any] = {"id": item["id"], "learner_text": item["learner_text"]}
        if getattr(client, "exhausted", False):
            row.update(status="not_run", reason="spending cap reached")
            rows[surface].append(row)
            continue
        if hasattr(client, "role"):
            client.role = "app"
        try:
            output = S.SURFACES[surface](item, client)
        except Exception as exc:  # noqa: BLE001 - one crashing item must not stop the run
            output = {"failure": f"crash: {type(exc).__name__}: {S.compact(exc, 200)}"}
        if getattr(client, "exhausted", False):
            row.update(status="not_run", reason="spending cap reached during the app's own call")
            rows[surface].append(row)
            continue
        verdicts = dict(S.checks(surface, item, output))
        row["output"] = output
        row["failure"] = output.get("failure")
        if output.get("failure"):
            # The learner saw a fallback: the item scores 0 and the judge is not paid for.
            row.update(status="scored", verdicts=verdicts, score=0.0)
            rows[surface].append(row)
            if progress:
                progress(f"{surface} {item['id']}: failed ({output['failure']})")
            continue
        if hasattr(judge_client, "role"):
            judge_client.role = "judge"
        try:
            verdicts.update(judge_item(judge_client, surface, item, output, model=judge_model))
        except BudgetExhausted:
            row.update(status="not_run", reason="spending cap reached before the judge")
            rows[surface].append(row)
            continue
        except Exception as exc:  # noqa: BLE001
            row.update(status="not_run", reason=f"judge failed: {S.compact(exc, 160)}", output=output)
            rows[surface].append(row)
            continue
        row.update(status="scored", verdicts=verdicts, score=item_score(verdicts, surface))
        rows[surface].append(row)
        if progress:
            progress(f"{surface} {item['id']}: {row['score'] if row['score'] is None else round(row['score'] * 100)}")
    return {
        "criteria_version": CRITERIA_VERSION,
        "set_versions": {s: set_version(s) for s in surfaces},
        "judge_model": judge_model,
        "surfaces": {s: summarize(s, rows[s]) for s in surfaces},
        "items": rows,
    }


def rejudge(
    result: dict, *, judge_client: Any, judge_model: str, progress: Callable[[str], None] | None = None
) -> dict:
    """The same app answers scored by another judge: every judged item of ``result`` is
    asked again, the deterministic checks and the fallbacks stay as they were. This is how
    a judge change is calibrated before it replaces the old one."""

    rows_out: dict[str, list[dict]] = {}
    for surface, rows in result["items"].items():
        items = {item["id"]: item for item in S.load_items(surface)}
        checked = {c.id for c in CRITERIA[surface] if c.by == "check"}
        rows_out[surface] = []
        for row in rows:
            row = dict(row)
            item = items.get(row["id"])
            if row["status"] != "scored" or row.get("failure") or item is None or "output" not in row:
                rows_out[surface].append(row)
                continue
            if getattr(judge_client, "exhausted", False):
                row.update(status="not_run", reason="spending cap reached")
                rows_out[surface].append(row)
                continue
            verdicts = {cid: tuple(v) for cid, v in row["verdicts"].items() if cid in checked}
            try:
                verdicts.update(judge_item(judge_client, surface, item, row["output"], model=judge_model))
            except Exception as exc:  # noqa: BLE001 - one failed judgement must not stop the rest
                row.update(status="not_run", reason=f"judge failed: {S.compact(exc, 160)}")
                rows_out[surface].append(row)
                continue
            row.update(verdicts=verdicts, score=item_score(verdicts, surface))
            rows_out[surface].append(row)
            if progress:
                progress(f"{surface} {row['id']}: {row['score'] if row['score'] is None else round(row['score'] * 100)}")
    out = dict(result)
    out.update(
        judge_model=judge_model, rejudged_from=result.get("judge_model"),
        surfaces={s: summarize(s, rows_out[s]) for s in rows_out}, items=rows_out,
    )
    return out


def judge_agreement(a: dict, b: dict) -> dict[str, dict]:
    """Per surface: both scores and how often the two judges gave the same verdict on
    the same judged criterion of the same answer (pass/fail/na)."""

    report: dict[str, dict] = {}
    for surface, rows_a in a["items"].items():
        rows_b = {row["id"]: row for row in b["items"].get(surface, [])}
        same = total = 0
        flips: list[str] = []
        for row in rows_a:
            other = rows_b.get(row["id"])
            if not other or row["status"] != "scored" or other["status"] != "scored" or row.get("failure"):
                continue
            for criterion in judged(surface):
                va = (row["verdicts"].get(criterion.id) or ("na", ""))[0]
                vb = (other["verdicts"].get(criterion.id) or ("na", ""))[0]
                total += 1
                if va == vb:
                    same += 1
                else:
                    flips.append(f"{row['id']} {criterion.id}: {va}→{vb}")
        report[surface] = {
            "score_a": a["surfaces"][surface]["score"], "score_b": b["surfaces"][surface]["score"],
            "agreement": round(same / total, 3) if total else None, "verdicts": total, "flips": flips,
        }
    return report


