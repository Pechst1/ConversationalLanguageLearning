JUDGE_SYSTEM = (
    "You grade one answer of a French-learning app against fixed written criteria. The learner is a "
    "beginner who writes French with mistakes on purpose or by accident; the app answers them. For "
    "EACH criterion give verdict pass, fail or na, and a reason of at most 20 words quoting the output "
    "where it helps. Use na only where the criterion itself says when it does not apply. Treat the "
    "ground_truth as correct. Judge only what each criterion asks, nothing else, and be strict: a "
    "pass means a careful teacher would sign it. Write every reason in English. Answer with JSON only: "
    '{"criteria": [{"id": "<criterion id>", "verdict": "pass|fail|na", "reason": "..."}]}'
)


def judge_payload(surface: str, item: dict, output: dict) -> dict:
    context: dict[str, Any] = {}
    if surface == "scene":
        context = {
            "character": item["character_id"],
            "character_asked": item["scene"]["opening_line_fr"],
            "objective": item["scene"]["objective_native"],
            "objective_semantics": item["scene"].get("objective_semantics"),
            "earlier_exchanges": item.get("history") or [],
        }
    elif surface == "forge":
        context = {"task": item["prompt"], "instruction": item.get("instruction", "Write it in French."),
                   "stored_example": item["example_answer"]}
    else:
        corr = item["correspondent"]
        context = {"correspondent": corr["name"], "register_of_thread": corr.get("register", "tu"), "their_letter": corr["letter"]}
    shown = {key: value for key, value in output.items() if key not in {"failure"}}
    return {
        "surface": SURFACE_TITLES[surface],
        "criteria": [{"id": c.id, "text": c.text} for c in judged(surface)],
        "learner_level": item.get("level", "A1"),
        "context": context,
        "learner_text": item["learner_text"],
        "ground_truth": item.get("truth") or {},
        "output_shown_to_learner": shown,
    }


def _ask(client: Any, messages: list[dict], kwargs: dict[str, Any]) -> Any:
    """One judge call; a provider that refuses temperature or an effort is asked without it."""

    from app.services.llm_service import LLMProviderError

    kwargs = dict(kwargs)
    for _attempt in range(3):
        try:
            return client.generate_chat_completion(messages, **kwargs)
        except LLMProviderError as exc:
            text = str(exc).lower()
            if "gold budget" in text:
                raise BudgetExhausted(str(exc)) from exc
            if "temperature" in text and "temperature" in kwargs:
                kwargs.pop("temperature")
                continue
            if "reasoning" in text and "reasoning_effort" in kwargs:
                kwargs.pop("reasoning_effort")
                continue
            raise
    raise LLMProviderError("judge gave no answer")


def judge_item(client: Any, surface: str, item: dict, output: dict, *, model: str) -> dict[str, tuple[str, str]]:
    if surface == "page":
        return judge_page(client, item, output, model=model)
    if surface == DAY_SURFACE:
        return judge_day(client, item, output, model=model)
    payload = judge_payload(surface, item, output)
    messages = [{"role": "user", "content": json.dumps(payload, ensure_ascii=False)}]
    result = _ask(client, messages, {
        "system_prompt": JUDGE_SYSTEM, "model": model, "max_tokens": 1000, "temperature": 0.0,
        "response_format": {"type": "json_object"}, "reasoning_effort": "low", "request_timeout": 90,
    })
    return parse_verdicts(surface, result.content)


#: A page question passes at this rating or above (the story judge's gate for «natural»).
PAGE_PASS = 4


def judge_page(client: Any, item: dict, output: dict, *, model: str) -> dict[str, tuple[str, str]]:
    """The story judge's own rubric (``season.story_judge``): each question rated 1 to 5.
    The verdict is ``pass`` from :data:`PAGE_PASS` up; the reason starts with «n/5»."""

    from app.services.season import story_judge as SJ

    page = SJ.Page(
        source="gold", key=item.get("segment_day") or item["id"], title=output.get("title") or "",
        kind="generated", level=item.get("level", "A2"),
        items=SJ.parse_lines(output.get("page_lines") or []), day=item.get("season_day"),
    )
    return rate_page(client, page, [c.id for c in judged("page")], model=model)


def act_page(item: dict, act: dict, *, first_act: str | None = None):
    """One act of a day as the story judge reads it: a page of its own, «Le fil» or a
    later act (``story_judge.Page.act``), a later one with the day's first act to compare."""

    from app.services.season import story_judge as SJ

    return SJ.Page(
        source="gold", key=f"{item.get('segment_day') or item['id']} {act['role']}", title=act.get("title") or "",
        kind="generated", level=item.get("level", "A2"), items=SJ.parse_lines(act.get("page_lines") or []),
        day=item.get("season_day"), previous_summary=first_act, act=act["role"],
    )


def judge_day(client: Any, item: dict, output: dict, *, model: str) -> dict[str, tuple[str, str]]:
    """Each act the day wrote, read by the story judge as a page of its own on the page's
    questions; a later act is also asked «new» against the day's first act (the weekly
    judge comparing act 2 with act 1). Verdicts are keyed ``<role>.<question>``; a dropped
    act has only its ``served`` check (``surfaces.checks``)."""

    from app.services.season import story_judge as SJ

    acts = [act for act in output.get("acts") or [] if not act.get("failure") and not act.get("not_run")]
    first = next((act for act in acts if act["role"] == SJ.ACT_ROLES[0]), None)
    summary = SJ.summarize(act_page(item, first)) if first else None
    verdicts: dict[str, tuple[str, str]] = {}
    for act in acts:
        page = act_page(item, act, first_act=None if act is first else summary)
        questions = [c.id for c in judged(DAY_SURFACE) if c.id != "new" or (page.later_act and page.previous_summary)]
        for key, verdict in rate_page(client, page, questions, model=model).items():
            verdicts[f"{act['role']}.{key}"] = verdict
    return verdicts


def rate_page(client: Any, page: Any, questions: list[str], *, model: str) -> dict[str, tuple[str, str]]:
    """One story-judge reading of ``page`` on ``questions``, each rated 1 to 5."""

    from app.services.season import story_judge as SJ

    system, user = SJ.rubric_messages(page, questions)
    result = _ask(client, [{"role": "user", "content": user}], {
        "system_prompt": system, "model": model, "max_tokens": SJ.DEFAULT_MAX_TOKENS, "temperature": 0.0,
        "response_format": {"type": "json_object"}, "reasoning_effort": SJ.DEFAULT_REASONING_EFFORT,
        "request_timeout": SJ.REQUEST_TIMEOUT_SECONDS,
    })
    verdicts: dict[str, tuple[str, str]] = {}
    for key, cell in SJ.read_scores(SJ._json_object(result.content), questions).items():
        rating = cell.get("score")
        if rating is None:
            verdicts[key] = ("fail", "judge: no verdict")
        else:
            reason = S.compact(f"{rating}/5 {cell.get('reason') or ''}", 200)
            verdicts[key] = ("pass" if rating >= PAGE_PASS else "fail", reason)
    return verdicts


def page_ratings(verdicts: dict[str, tuple[str, str]]) -> dict[str, int]:
    out = {}
    for key, (_verdict, reason) in verdicts.items():
        head = str(reason).split("/5", 1)[0]
        if head.isdigit():
            out[key] = int(head)
    return out


def parse_verdicts(surface: str, content: str) -> dict[str, tuple[str, str]]:
    """The judge's answer, one verdict per judged criterion. A missing or unreadable
    verdict counts as a fail of the judge ("judge: no verdict"), never as a pass."""

    try:
        rows = json.loads(content).get("criteria") or []
    except (json.JSONDecodeError, AttributeError):
        rows = []
    by_id = {str(row.get("id")): row for row in rows if isinstance(row, dict)}
    verdicts: dict[str, tuple[str, str]] = {}
    for criterion in judged(surface):
        row = by_id.get(criterion.id) or {}
        verdict = str(row.get("verdict") or "").strip().lower()
        if verdict not in {"pass", "fail", "na"}:
            verdicts[criterion.id] = ("fail", "judge: no verdict")
        else:
            verdicts[criterion.id] = (verdict, S.compact(row.get("reason"), 200))
    return verdicts


