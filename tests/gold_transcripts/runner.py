def marker_entry(result: dict) -> dict:
    return {
        "date": result["date"],
        "label": result["label"],
        "criteria": result["criteria_version"],
        "judge": result.get("judge_model"),
        "sets": sets_digest(result),
        "scores": {s: v["score"] for s, v in result["surfaces"].items()},
        "spent": round(result.get("spent_usd", 0.0), 4),
    }


def sets_digest(result: dict) -> str:
    blob = json.dumps(result.get("set_versions") or {}, sort_keys=True)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()[:8]


def parse_history(bodies: list[str]) -> list[dict]:
    entries = []
    for body in bodies:
        start = body.find(MARKER)
        if start < 0:
            continue
        end = body.find("-->", start)
        try:
            entries.append(json.loads(body[start + len(MARKER) : end].strip()))
        except json.JSONDecodeError:
            continue
    return sorted(entries, key=lambda e: e.get("date", ""))


def issue_comment_bodies(issue: int = DIGEST_ISSUE) -> list[str]:
    bodies: list[str] = []
    page = 1
    while True:
        out = subprocess.run(  # noqa: S603 - fixed gh argv
            ["gh", "api", f"/repos/{REPO_SLUG}/issues/{issue}/comments?per_page=100&page={page}"],  # noqa: S607
            capture_output=True, text=True, check=False,
        )
        if out.returncode != 0:
            raise RuntimeError(f"gh api failed: {(out.stderr or out.stdout).strip()}")
        batch = json.loads(out.stdout or "[]")
        bodies += [c.get("body") or "" for c in batch]
        if len(batch) < 100:
            return bodies
        page += 1


def post_comment(body: str, issue: int = DIGEST_ISSUE) -> str:
    out = subprocess.run(  # noqa: S603 - fixed gh argv
        ["gh", "api", "-X", "POST", f"/repos/{REPO_SLUG}/issues/{issue}/comments", "--input", "-"],  # noqa: S607
        input=json.dumps({"body": body}), capture_output=True, text=True, check=False,
    )
    if out.returncode != 0:
        raise RuntimeError(f"gh api failed: {(out.stderr or out.stdout).strip()}")
    return json.loads(out.stdout).get("html_url", "")


#: The judge of the entries written before the history recorded one.
FIRST_JUDGE = "gpt-6.1-sol"


def entry_judge(entry: dict) -> str:
    return entry.get("judge") or FIRST_JUDGE


def trend_cells(history: list[dict], result: dict, surface: str, nights: int = 7) -> tuple[str, str]:
    """(change vs the last comparable night, the last ``nights`` scores) for a surface."""

    same = [
        e for e in history
        if e.get("label") == result["label"] and e.get("criteria") == result["criteria_version"]
        and entry_judge(e) == result.get("judge_model") and e.get("date") != result["date"] and (e.get("scores") or {}).get(surface) is not None
    ]
    now = result["surfaces"][surface]["score"]
    series = [e["scores"][surface] for e in same][-(nights - 1):] + ([now] if now is not None else [])
    trail = " → ".join(f"{v:.0f}" for v in series) if series else "–"
    if not same or now is None:
        return "first run", trail
    delta = now - same[-1]["scores"][surface]
    return (f"{delta:+.0f}" if abs(delta) >= 0.5 else "="), trail


def render_report(result: dict, history: list[dict]) -> str:
    label = result["label"]
    title = f"## Gold transcripts · {result['date']}" + ("" if label == "production" else f" · {label}")
    lines = [
        title, "",
        "Fixed learner inputs from the live walks, run against the production prompts and models and scored "
        "by a judge on fixed written criteria (`tests/gold_transcripts/`). A story fix is proven when its "
        "surface's score moves.", "",
        "| surface | score | vs last run | last runs | scored | weakest criterion |",
        "|---|---|---|---|---|---|",
    ]
    for surface, summary in result["surfaces"].items():
        delta, trail = trend_cells(history, result, surface)
        weakest = "–"
        rates = []
        for cid, frac in summary["criteria"].items():
            passed, total = (int(x) for x in frac.split("/"))
            rates.append((passed / total, cid, frac))
        if rates:
            rate, cid, frac = min(rates)
            weakest = f"`{cid}` {frac}" if rate < 1 else "none"
        score = "–" if summary["score"] is None else f"**{summary['score']:.0f}**"
        scored = f"{summary['scored']}/{summary['items']}"
        if summary["failed_outright"]:
            scored += f" ({summary['failed_outright']} fallback)"
        lines.append(f"| {SURFACE_TITLES[surface]} | {score} | {delta} | {trail} | {scored} | {weakest} |")
    page = result["surfaces"].get("page")
    if page and page.get("seconds_median") is not None:
        means = ", ".join(f"{k} {v['mean']:.1f}" for k, v in (page.get("ratings") or {}).items())
        lines += ["", (
            f"Night writer's page: {page['lost']} of {page['scored']} days lost, "
            f"{page['seconds_median']:.0f} s median and {page['seconds_max']:.0f} s slowest per page "
            f"(budget {S.PAGE_BUDGET_SECONDS} s); mean ratings out of 5: {means or '–'}."
        )]
    models = result.get("models") or {}
    model_line = ", ".join(f"{k}={v}" for k, v in models.items() if v is not None)
    lines += [
        "",
        f"Spent US${result.get('spent_usd', 0.0):.2f} of a US${result.get('cap_usd', 0.0):.2f} cap · judge `{result['judge_model']}` · "
        f"criteria `{result['criteria_version']}` · models: {model_line or 'app defaults'}.",
    ]
    previous = [e for e in history if e.get("label") == label and e.get("date") != result["date"]]
    if previous and previous[-1].get("criteria") != result["criteria_version"]:
        lines.append("The criteria changed since the last run: the trend starts again.")
    elif previous and entry_judge(previous[-1]) != result.get("judge_model"):
        lines.append(f"The judge changed since the last run (was `{entry_judge(previous[-1])}`): the trend starts again.")
    elif previous and previous[-1].get("sets") not in (None, sets_digest(result)):
        lines.append("The gold inputs changed since the last run (see the PR that changed them): read the change with that in mind.")
    lost = []
    for surface, rows in result["items"].items():
        for row in rows:
            if row["status"] != "scored":
                lost.append(f"- {surface} `{row['id']}`: not run ({row.get('reason')})")
                continue
            fails = [f"`{cid}` {reason}" for cid, (v, reason) in row["verdicts"].items() if v == "fail"]
            if fails:
                lost.append(f"- {surface} `{row['id']}` «{S.compact(row['learner_text'], 90)}»: " + "; ".join(fails[:3]))
    if lost:
        lines += ["", f"<details><summary>Where points were lost ({len(lost)})</summary>", "", *lost[:80], "", "</details>"]
    lines += ["", MARKER + json.dumps(marker_entry(result), ensure_ascii=False) + " -->"]
    return "\n".join(lines) + FOOTER
